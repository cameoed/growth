const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('src/beings_leads/dashboard/sales-engine.js','utf8');
const code=source.slice(source.indexOf('export function captureSalesLocation('),source.indexOf('export async function searchSalesWorkbench(')).replaceAll('export ','');
const nodes=new Map([['.engine-company-list',{scrollTop:125}],['.engine-company-workspace',{scrollTop:380}]]);
const context=vm.createContext({missionId:'test-mission',state:{tab:'queue',search:'software'},selectedTag:'starred',companySort:'newest',listOffset:50,pageSize:25,pageSizes:[10,25,50,100,250],selectedKey:'/companies/42',document:{querySelector:selector=>nodes.get(selector)},Number});
vm.runInContext(code,context);
const saved=context.captureSalesLocation();
context.state.search='';context.selectedKey='';context.listOffset=0;
assert.equal(context.restoreSalesLocation(saved),true);
assert.equal(context.selectedKey,'/companies/42');assert.equal(context.listOffset,50);
assert.equal(context.state.search,'software');assert.equal(context.selectedTag,'starred');
assert.equal(context.restoreSalesLocation({...saved,missionId:'another-mission',selectedKey:'/companies/99'}),false);
assert.equal(context.selectedKey,'/companies/42');
context.restoreSalesLocation({...saved,selectedKey:'/companies/../../settings',listOffset:-20,pageSize:123});
assert.equal(context.selectedKey,'');assert.equal(context.listOffset,0);assert.equal(context.pageSize,25);
for(const node of nodes.values())node.scrollTop=0;
context.restoreSalesScroll(saved);
assert.equal(nodes.get('.engine-company-list').scrollTop,125);assert.equal(nodes.get('.engine-company-workspace').scrollTop,380);
console.log('Refresh location validation, mission isolation and scroll restoration passed');
